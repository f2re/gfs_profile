def water_profile_missing(fields: dict) -> np.ndarray:
    """Missing cloud/water samples above the surface, supplied by the core.

    The cloud products require the level cloud fraction as well as liquid water.
    Never substitute the legacy water-only validity mask for missing cloud data.
    """
    return np.asarray(fields["cloud_profile_missing"], dtype=bool)


def icing_profile_missing(fields: dict, product: str) -> np.ndarray:
    """Select common view quality flags without dropping unavailable dewpoint."""
    if product == "composite":
        return np.asarray(fields["composite_profile_missing"], dtype=bool)
    missing = water_profile_missing(fields)
    if product.startswith("godske_"):
        missing = missing | np.asarray(fields["cloud_godske_profile_missing"], dtype=bool)
    return missing
